// Prints mod/tests/main-vectors.ts: layouts of a git checkout (files, directories) with the answer
// hooks/lib-config.mjs `mainCheckoutRoot` gives for each, computed on a real temp tree. The mod's mirror of that
// function (mod/view.ts) is tested against the same cases, which pins the two to one answer.
// Usage: node tests/gen-mod-main-vectors.mjs
import { mkdirSync, mkdtempSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { mainCheckoutRoot } from "../hooks/lib-config.mjs";

const R = realpathSync(mkdtempSync(join(tmpdir(), "ah-main-vectors.")));
const V = "/v";
const virtual = (s) => s.split(R).join(V);

// Each case: name, the files and directories under its own `<name>/`, and the checkout root asked about.
const cases = [
  { name: "linked-absolute", asks: "wt", dirs: ["main/.git/worktrees/wt", "wt"], files: { "wt/.git": "gitdir: @/main/.git/worktrees/wt\n", "main/.git/worktrees/wt/commondir": "../..\n" } },
  { name: "linked-relative", asks: "wt", dirs: ["main/.git/worktrees/wt", "wt"], files: { "wt/.git": "gitdir: ../main/.git/worktrees/wt\n", "main/.git/worktrees/wt/commondir": "../..\n" } },
  { name: "linked-absolute-commondir", asks: "wt", dirs: ["main/.git/worktrees/wt", "wt"], files: { "wt/.git": "gitdir: @/main/.git/worktrees/wt\n", "main/.git/worktrees/wt/commondir": "@/main/.git\n" } },
  { name: "linked-no-commondir", asks: "wt", dirs: ["main/.git/worktrees/wt", "wt"], files: { "wt/.git": "gitdir: @/main/.git/worktrees/wt\n" } },
  { name: "linked-nested-name", asks: "deep/wt", dirs: ["main/.git/worktrees/wt", "deep/wt"], files: { "deep/wt/.git": "gitdir: @/main/.git/worktrees/wt\n", "main/.git/worktrees/wt/commondir": "../..\n" } },
  { name: "submodule", asks: "sub", dirs: ["main/.git/modules/sub", "sub"], files: { "sub/.git": "gitdir: ../main/.git/modules/sub\n" } },
  { name: "normal-checkout", asks: "repo", dirs: ["repo/.git"], files: {} },
  { name: "malformed", asks: "wt", dirs: ["wt"], files: { "wt/.git": "this is not a gitdir pointer\n" } },
  { name: "bare-common-dir", asks: "wt", dirs: ["bare.git/worktrees/wt", "wt"], files: { "wt/.git": "gitdir: @/bare.git/worktrees/wt\n", "bare.git/worktrees/wt/commondir": "../..\n" } },
  { name: "no-git-entry", asks: "wt", dirs: ["wt"], files: {} },
];

let out = "// Generated by `node tests/gen-mod-main-vectors.mjs > mod/tests/main-vectors.ts`. Do not edit.\n";
out += "export type MainVector = { name: string; root: string; files: Record<string, string>; dirs: string[]; expected: string | null }\n";
out += "export const mainVectors: readonly MainVector[] = [\n";
for (const c of cases) {
  const base = join(R, c.name);
  const at = (rel) => join(base, rel);
  for (const d of c.dirs) mkdirSync(at(d), { recursive: true });
  const files = {};
  for (const [rel, text] of Object.entries(c.files)) {
    const real = text.split("@").join(base);
    mkdirSync(join(at(rel), ".."), { recursive: true });
    writeFileSync(at(rel), real);
    files[virtual(at(rel))] = virtual(real);
  }
  const expected = mainCheckoutRoot(at(c.asks));
  const entry = {
    name: c.name,
    root: virtual(at(c.asks)),
    files,
    dirs: c.dirs.map((d) => virtual(at(d))),
    expected: expected === null ? null : virtual(expected),
  };
  out += `  ${JSON.stringify(entry)},\n`;
}
out += "]\n";
rmSync(R, { recursive: true, force: true });
process.stdout.write(out);
